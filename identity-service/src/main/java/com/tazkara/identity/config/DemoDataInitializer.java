package com.tazkara.identity.config;

import com.tazkara.common.security.Role;
import com.tazkara.identity.domain.EmailAddress;
import com.tazkara.identity.domain.User;
import com.tazkara.identity.domain.UserFactory;
import com.tazkara.identity.repository.UserRepository;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.boot.ApplicationArguments;
import org.springframework.boot.ApplicationRunner;
import org.springframework.boot.autoconfigure.condition.ConditionalOnProperty;
import org.springframework.stereotype.Component;
import org.springframework.transaction.annotation.Transactional;



@Component
@ConditionalOnProperty(name = "tazkara.demo.enabled", havingValue = "true")
public class DemoDataInitializer implements ApplicationRunner {

    private static final Logger log = LoggerFactory.getLogger(DemoDataInitializer.class);

    private final UserRepository userRepository;
    private final UserFactory userFactory;
    private final Long expectedOrganizerId;

    public DemoDataInitializer(UserRepository userRepository, UserFactory userFactory,
                               @Value("${tazkara.demo.organizer-id}") Long expectedOrganizerId) {
        this.userRepository = userRepository;
        this.userFactory = userFactory;
        this.expectedOrganizerId = expectedOrganizerId;
    }

    // Ids are generated by the database; the organizer is created first so a fresh database gives it id 1,
    // which the event service uses as the owner of its demo event.
    @Override
    @Transactional
    public void run(ApplicationArguments args) {
        User organizer = createIfMissing("Omar Organizer", "organizer@tazkara.com", "Organizer123",
                Role.ORGANIZER, "Tazkara Demo Events");
        createIfMissing("Aya Attendee", "attendee@tazkara.com", "Attendee123", Role.ATTENDEE, null);

        if (!organizer.getId().equals(expectedOrganizerId)) {
            log.warn("Demo organizer has id {} but tazkara.demo.organizer-id is {}; the demo event will not belong to it",
                    organizer.getId(), expectedOrganizerId);
        }
    }

    private User createIfMissing(String name, String email, String password, Role role, String organization) {
        return userRepository.findByEmail(EmailAddress.of(email)).orElseGet(() -> {
            User user = userRepository.save(userFactory.create(name, email, password, role, organization));
            log.info("Demo {} account created: {}", role, email);
            return user;
        });
    }
}
